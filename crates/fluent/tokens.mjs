#!/usr/bin/env node
// Writes src/tokens.rs from reference/layout/tokens.json: every CSS variable of style.css as
// Chromium resolved it in each theme. Run it again whenever tokens.json changes:
//
//   node crates/fluent/tokens.mjs        (from the repository root)
//
// Alphas are written as Chromium stores them, a whole number of 255ths (rgba(255,255,255,0.786)
// paints with alpha 200/255; tokens.json rounds that to 0.784). The test in src/tokens.rs
// (`tokens_match_reference`) reads tokens.json again and checks every value.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, '..', '..', 'reference', 'layout', 'tokens.json');
const target = path.join(here, 'src', 'tokens.rs');
const json = JSON.parse(fs.readFileSync(source, 'utf8'));

// Theme-dependent colors, in style.css order. The accent ones (--accent-base/-light/-dark,
// --accent) come from the system accent at run time (theme.rs); fonts and sizes are separate.
const SKIP = new Set(['--accent-base', '--accent-light', '--accent-dark', '--accent', '--font', '--font-display', '--player-height', '--drawer-height']);
const names = Object.keys(json.tokens).filter((name) => !SKIP.has(name));
const field = (name) => name.slice(2).replace(/-/g, '_');

const color = ([r, g, b, a]) => {
    const alpha = Math.round(a * 255);
    const exact = alpha === 255 ? '1.0' : alpha === 0 ? '0.0' : `${alpha}.0 / 255.0`;
    return `Color::rgba(${r}, ${g}, ${b}, ${exact})`;
};

const palette = (theme) => names.map((name) => `    ${field(name)}: ${color(json.tokens[name][theme])},`).join('\n');
const docs = (name) => {
    const declared = json.tokens[name].declared;
    const text = Object.entries(declared).map(([theme, value]) => `${theme} ${value}`).join(', ');
    return `    /// \`${name}\`: ${text}`;
};

const out = `// Generated by tokens.mjs from reference/layout/tokens.json. Don't edit: run the script again.

use crate::color::Color;

/// The theme-dependent tokens of style.css (\`:root\` and its \`prefers-color-scheme: light\` block),
/// as Chromium resolved them. The accent tokens are in [\`crate::theme::Accent\`].
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Palette {
${names.map((name) => `${docs(name)}\n    pub ${field(name)}: Color,`).join('\n')}
}

pub const DARK: Palette = Palette {
${palette('dark')}
};

pub const LIGHT: Palette = Palette {
${palette('light')}
};

/// The tokens' CSS names, in the order of the fields (for the test and for debugging).
pub const NAMES: [&str; ${names.length}] = [${names.map((name) => JSON.stringify(name)).join(', ')}];

impl Palette {
    /// The fields in the order of [\`NAMES\`].
    pub fn values(&self) -> [Color; ${names.length}] {
        [${names.map((name) => `self.${field(name)}`).join(', ')}]
    }
}

/// \`--player-height\`: the player window's client height without the drawer.
pub const PLAYER_HEIGHT: f32 = ${json.tokens['--player-height'].dark}.0;
/// \`--drawer-height\`: what the playlist drawer adds.
pub const DRAWER_HEIGHT: f32 = ${json.tokens['--drawer-height'].dark}.0;

/// The accent the reference was rendered with (the Windows default blue as \`AccentPalette\` gives it).
pub const REFERENCE_ACCENT: [&str; 3] = [${JSON.stringify(json.accent.base)}, ${JSON.stringify(json.accent.light)}, ${JSON.stringify(json.accent.dark)}];
/// The CSS fallback (\`--accent-base\` / \`-light\` / \`-dark\` in style.css), used when the system has
/// no accent to give (macOS).
pub const CSS_ACCENT: [&str; 3] = [${JSON.stringify(json.tokens['--accent-base'].declared.dark)}, ${JSON.stringify(json.tokens['--accent-light'].declared.dark)}, ${JSON.stringify(json.tokens['--accent-dark'].declared.dark)}];

#[cfg(test)]
mod tests {
    use super::*;
    use crate::theme::{Accent, Theme};

    fn reference() -> serde_json::Value {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../reference/layout/tokens.json");
        serde_json::from_str(&std::fs::read_to_string(path).expect("reference/layout/tokens.json")).expect("valid JSON")
    }

    // Chromium keeps a legacy rgba() alpha as a byte: the same byte as the reference's value.
    fn same(color: Color, value: &serde_json::Value, what: &str) {
        let parts: Vec<f64> = value.as_array().expect(what).iter().map(|v| v.as_f64().expect(what)).collect();
        assert_eq!([color.r as f64, color.g as f64, color.b as f64], [parts[0], parts[1], parts[2]], "{what}");
        assert_eq!((color.a as f64 * 255.0).round(), (parts[3] * 255.0).round(), "{what} alpha");
        assert!((color.a as f64 * 255.0 - (color.a as f64 * 255.0).round()).abs() < 1e-4, "{what}: alpha is a whole number of 255ths");
    }

    #[test]
    fn tokens_match_reference() {
        let json = reference();
        let tokens = json["tokens"].as_object().expect("tokens");
        let mut checked = 0;
        for (palette, theme) in [(&DARK, "dark"), (&LIGHT, "light")] {
            for (name, value) in NAMES.iter().zip(palette.values()) {
                same(value, &tokens[*name][theme], &format!("{name} ({theme})"));
                checked += 1;
            }
            // The accent, as bridge.js injects it and the CSS resolves it.
            let accent = Accent::parse(&REFERENCE_ACCENT[0], &REFERENCE_ACCENT[1], &REFERENCE_ACCENT[2]).expect("accent");
            let resolved = Theme::new(theme == "dark", accent);
            same(resolved.accent_base, &tokens["--accent-base"][theme], "--accent-base");
            same(resolved.accent_light, &tokens["--accent-light"][theme], "--accent-light");
            same(resolved.accent_dark, &tokens["--accent-dark"][theme], "--accent-dark");
            same(resolved.accent, &tokens["--accent"][theme], &format!("--accent ({theme})"));
            same(resolved.on_accent,&tokens["--on-accent"][theme], &format!("--on-accent ({theme})"));
            checked += 5;
        }
        // Every token in the file is either here or one of the non-color ones.
        let skipped = ["--accent-base", "--accent-light", "--accent-dark", "--accent", "--font", "--font-display", "--player-height", "--drawer-height"];
        assert_eq!(tokens.len(), NAMES.len() + skipped.len());
        assert_eq!(json["accent"]["base"], REFERENCE_ACCENT[0]);
        assert_eq!(tokens["--player-height"]["dark"].as_f64(), Some(PLAYER_HEIGHT as f64));
        assert_eq!(tokens["--drawer-height"]["dark"].as_f64(), Some(DRAWER_HEIGHT as f64));
        assert_eq!(tokens["--font"]["dark"].as_str(), Some(crate::text::FONT_STACK));
        assert_eq!(tokens["--font-display"]["dark"].as_str(), Some(crate::text::FONT_STACK_DISPLAY));
        assert!(checked > 60);
    }
}
`;

fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)}: ${names.length} tokens per theme`);
